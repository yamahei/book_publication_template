#!/usr/bin/env bash
# ==============================================================================
# md2kdp.sh - 設定ファイルに基づいてEPUBとPDFを一括生成するスクリプト
#
# 使用法:
#   ./bin/md2kdp.sh
# ==============================================================================

set -eu
export MSYS_NO_PATHCONV=1

SCRIPT_DIR="$(cd "$(dirname "$0")" && (pwd -W 2>/dev/null || pwd))"

echo "=================================================="
echo "KDP出版用データ一括生成を開始します"
echo "=================================================="

echo ""
echo "[1/2] EPUB 生成中..."
"${SCRIPT_DIR}/md2epub.sh"

echo ""
echo "[2/2] PDF 生成中..."
"${SCRIPT_DIR}/md2pdf.sh"

echo ""
echo "=================================================="
echo "すべてのパブリッシュが正常に完了しました！"
echo "出力先: book/dist/"
echo "=================================================="
